/**
 * Builds supabase/seed.sql from the bundled demo content, so the database and demo mode always
 * show the same texts. The SQL is idempotent: running it again updates rows by slug and never
 * duplicates anything. (Content an editor changed in the admin panel is overwritten for the
 * slugs listed here, so seed once, then edit in the admin panel.)
 */
import {
  articleToRow,
  contactToRow,
  exerciseToRow,
  questionToRow,
  testToRow,
  topicToRow,
} from "../src/lib/content/db";
import { articles, exercises, helpContacts, tests, topics } from "../src/content";

class Raw {
  constructor(readonly sql: string) {}
}

const str = (s: string) => `'${s.replace(/'/g, "''")}'`;

/** Columns that hold a JSON array of strings (everything else that is a string[] is a text[] column). */
const JSON_ARRAY_COLUMNS = new Set(["sources"]);

function value(v: unknown, column = ""): string {
  if (v instanceof Raw) return v.sql;
  if (Array.isArray(v) && JSON_ARRAY_COLUMNS.has(column)) return `${str(JSON.stringify(v))}::jsonb`;
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v) && v.every((x) => typeof x === "string")) {
    return v.length === 0 ? "'{}'::text[]" : `array[${v.map(str).join(", ")}]::text[]`;
  }
  if (typeof v === "object" || Array.isArray(v)) return `${str(JSON.stringify(v))}::jsonb`;
  return str(String(v));
}

const topicId = (slug: string) => new Raw(`(select id from public.topics where slug = ${str(slug)})`);
const testId = (slug: string) => new Raw(`(select id from public.tests where slug = ${str(slug)})`);

function upsert(table: string, rows: Record<string, unknown>[], conflict: string): string {
  return rows
    .map((row) => {
      const cols = Object.keys(row);
      const updates = cols.filter((c) => c !== conflict).map((c) => `${c} = excluded.${c}`);
      return (
        `insert into public.${table} (${cols.join(", ")})\n` +
        `values (${cols.map((c) => value(row[c], c)).join(", ")})\n` +
        `on conflict (${conflict}) do update set ${updates.join(", ")};`
      );
    })
    .join("\n\n");
}

export function generateSeed(): string {
  const parts: string[] = [
    "-- Generated by `npm run seed:generate` from src/content. Do not edit by hand.",
    "-- Demo content in Kazakh and Russian. Idempotent: safe to run more than once.",
    "begin;",
  ];

  parts.push("-- Topics", upsert("topics", topics.map(topicToRow), "slug"));

  parts.push("-- Exercises", upsert("exercises", exercises.map(exerciseToRow), "slug"));
  for (const e of exercises) {
    for (const slug of e.topicSlugs) {
      parts.push(
        `insert into public.exercise_topics (exercise_id, topic_id)\n` +
          `select e.id, t.id from public.exercises e, public.topics t\n` +
          `where e.slug = ${str(e.slug)} and t.slug = ${str(slug)}\n` +
          `on conflict do nothing;`,
      );
    }
  }

  parts.push(
    "-- Articles",
    upsert(
      "articles",
      articles.map((a) => ({ ...articleToRow(a), topic_id: topicId(a.topicSlug) })),
      "slug",
    ),
  );

  parts.push(
    "-- Tests",
    upsert(
      "tests",
      tests.map((t) => ({ ...testToRow(t), topic_id: topicId(t.topicSlug) })),
      "slug",
    ),
  );
  for (const t of tests) {
    parts.push(`delete from public.test_questions where test_id = ${testId(t.slug).sql};`);
    t.questions.forEach((q, i) => {
      const row = { test_id: testId(t.slug), ...questionToRow(q), sort_order: i + 1 };
      const cols = Object.keys(row);
      parts.push(
        `insert into public.test_questions (${cols.join(", ")})\nvalues (${cols.map((c) => value(row[c as keyof typeof row], c)).join(", ")});`,
      );
    });
  }

  parts.push("-- Help contacts (only added when the number is not in the table yet)");
  for (const c of helpContacts) {
    const row = contactToRow(c);
    const cols = Object.keys(row);
    parts.push(
      `insert into public.help_contacts (${cols.join(", ")})\n` +
        `select ${cols.map((col) => value(row[col], col)).join(", ")}\n` +
        `where not exists (select 1 from public.help_contacts where phone = ${str(c.phone)});`,
    );
  }

  parts.push("commit;");
  return parts.join("\n\n") + "\n";
}
