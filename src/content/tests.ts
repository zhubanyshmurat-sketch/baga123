import type { L, Level, PsyTest, TestQuestion, TestThreshold } from "@/lib/content/types";

/*
 * Self-assessment tests. All of them are orientational ("ориентировочные") and use original
 * wording, not licensed questionnaires. The text, scoring and thresholds MUST be reviewed by
 * a practising psychologist before launch (see README → Launch checklist).
 *
 * Scoring convention: every test scores 0–3 per question; a higher total means "more of what the
 * title names". Reverse-keyed questions have reversed weights but keep the answer order.
 */

const frequency: L[] = [
  { kk: "Ешқашан", ru: "Никогда" },
  { kk: "Кейде", ru: "Иногда" },
  { kk: "Жиі", ru: "Часто" },
  { kk: "Әрдайым дерлік", ru: "Почти всегда" },
];

const agreement: L[] = [
  { kk: "Мүлде келіспеймін", ru: "Совсем не согласен(на)" },
  { kk: "Көбіне келіспеймін", ru: "Скорее не согласен(на)" },
  { kk: "Көбіне келісемін", ru: "Скорее согласен(на)" },
  { kk: "Толық келісемін", ru: "Полностью согласен(на)" },
];

interface QOptions {
  scale: "frequency" | "agreement";
  /** Reverse-keyed: the first answer scores highest. */
  reverse?: boolean;
  /** Sensitive question: answers with value >= alertFrom show the support block. */
  alertFrom?: number;
}

function question(id: string, text: L, { scale, reverse, alertFrom }: QOptions): TestQuestion {
  const labels = scale === "frequency" ? frequency : agreement;
  return {
    id,
    text,
    sensitive: alertFrom !== undefined || undefined,
    options: labels.map((label, value) => ({
      value,
      weight: reverse ? 3 - value : value,
      label,
      ...(alertFrom !== undefined && value >= alertFrom ? { alert: true } : {}),
    })),
  };
}

function level(
  lvl: Level,
  range: [number, number],
  title: L,
  summary: L,
  recommendations: { kk: [string, string, string]; ru: [string, string, string] },
  exerciseSlugs: string[],
  specialist: L,
): TestThreshold {
  return {
    level: lvl,
    min: range[0],
    max: range[1],
    title,
    summary,
    recommendations: { kk: [...recommendations.kk], ru: [...recommendations.ru] },
    exerciseSlugs,
    specialist,
  };
}

